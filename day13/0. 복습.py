# 파일 입출력


# 파일명 : .확장자가 붙어있는 파일

# 파일의 경로
# 1. 절대 경로
# 경로의 시작점을 루트폴더로 지정한 경로

# 루트 폴더 : 모든 파일이 존재하는 폴더
# window -> C:
# 맥, 리눅스 -> \


# 2. 상대 경로
# 현재 실행하는 프로그램이 있는 디렉터리(폴더)에서 시작하는 경로

# . : 현재 디렉터리를 나타내는 문자
# ..: .의 상위 디렉터리


# open() 함수
# 작업할 파일 객체를 생성할 수 있다.
# open(파일명, 모드)


# 모드
# 작업 종류를 문자 2개를 사용해서 지정할 수 있다.

# 입출력
# 입력
# r (read) 읽기

# 쓰기
# w (write) 쓰기          : 파일이 이미 존재해도 덮어써서 새로 생성
# a (append) 추가         : 파일의 끝에서부터 내용을 추가
# x (exclusive) 베타적 추가  : 이미 존재하면 오류발생

# 파일의 종류 지정
# t (text)  :   텍스트 파일
# b (binary)    : 바이너리 파일 (텍스트 파일이외 모든 파일종류)


# close()
# 파일객체에 대한 작업이 끝났다면 close()로 파일을 닫을 수 있다.
