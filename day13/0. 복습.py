# 예외 처리의 목적
# 예외로 인해 프로그램이 강제 종료되는 것을 막고
# 그 예외에 대한 정보를 전달
# 그 후 예외에 대한 문제 해결

# 예외 처리
# 1. 고전적 처리 방식
# --> 조건식

# 문제점
# 개발자가 모든 예외가 발생하는 경우의 수를 알고있어야한다.
# 복합적인 이유로 예외가 발생하는 경우

# 2. 클래스, try문을 이용한 처리 방법

# 예외들의 최상위 부모 Exception

# 컴파일 예외    : 코드를 분석하는 시간에 발생한 오류
# 런타임 예외    : 코드 문법적으로는 맞지만 실행시켜보니 예상치 못한 상황으로 발생하는 오류

# try - except문

# try:
#   예외가 발생할 가능성이 있는 코드
# except Exception:
#   Exception예외에 대해 실행할 코드
# except Exception2:
#   Exception2예외에 대해 실행할 코드
# else:
#   try문에서 예외가 밝생하지 않았을 때 실행할 코드
# finally:
#   무슨일이 있어도 실행되는 코드블럭


# 강제로 예외 발생시키기 (예외 던지기)
