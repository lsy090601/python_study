# 반복문의 종류 2가지!
# while문, for문

# while문으로 구현된 것을 for문으로, for문으로 구현된 것을 while문으로 변환이 가능하다

# while문 같은 경우, 반복횟수가 정해져있지않고 특정 종료조건을 알고있을 때
# for문 같은 경우, 반복횟수가 정해져있거나, 어떤 데이터(iterable 등)를 순회할 때 구현하기가 편하다.





# while문
# 특정 조건을 만족하는 동안 계속해서 코드를 반복 수행하는 반복문
# ex) 변수 A의 값이 10보다 작은동안에는 계속 반복해라
#     변수 A의 값이 -1이 될 때까지 계속 반복해라


# 기본 형태
# while 조건식:
#   반복 실행할 코드

# 실행 순서
# 1. while문에 프로그램이 도착
# 2. 조건식을 확인
# 3. 조건식이 True  : 코드블럭을 실행
#    조건식이 False : 코드블럭을 무시하고 코드를 진행
# 3 - 2. 코드블럭을 실행 후 다시 2번으로 이동한다.

# while 1:
#     print("hello")

# 조건식이 정해져있는 하드코딩의 형태이다.
# 반복문이 실행되는 동안 조건식의 결과를 바꿀 수 없다.
# --> 결과를 바꿀 수 없어서 while문에 갇히게 된다
# ----> 무한루프문 (조건식이 항상 참인 반복문)


