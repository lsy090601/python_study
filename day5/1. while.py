# 반복문의 중첩
day = 5
while day <= 8: # 5 ~ 8까지 4번 반복
    hour = 1
    print("코드 실행 위치 확인1")
    while hour <= 3: # 1 ~ 3까지 3번 반복
        print(f'{day}일차 {hour}교시입니다.')
        # print("코드 실행 위치 확인3")
        hour += 1
        # hour이 4가되면서 코드가 끝난다.
    print("코드 실행 위치 확인2")
    day += 1
# 반복문이 중첩되면 안쪽 반복문의 반복횟수 * 감싸고 있는 반복문의 횟수 만큼 코드가 실행된다
# 반복문 내에서 변수의 초기화를 진행하면 반복문이 실행될 때마다 새로 초기화가 일어난다. 따라서 코드의 작성 위치를 잘 확인해야한다.












































































