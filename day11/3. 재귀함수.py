# 최대 공약수 구하기

# 유클리드 호재법
# 숫자 A와 B가 있을 때 (A > B)
# 두 수의 최대 공약수는
# A를 B로 나눈 나머지를 n이라고 했을 때 (A % B == n)
# n이 0이되면 B가 두 수의 최대공약수라는 법칙

# 만약 n이 0이아니면 B는 A로 n은 B로 이동한 후 다시 연산을 진행

# ex) 12, 8
# 12 % 8 == 4
# 8 % 4 == 0
# 4가 12와 8의 최대 공약수구나!


# 반복문
def gcd_w(a, b): # gcd --> 최대공약수
    n = a % b
    while n != 0:
        a = b
        b = n
        n = a % b
    return b

print(gcd_w(12, 8)) # 4
print(gcd_w(32, 8)) # 8


def gcd(a, b):
    if b == 0:
        return a
    return gcd(b, a % b)
    # 다음 재귀 시 a에 b를 b에 n값을 넘겨서 실행

print(gcd(12, 8)) # 4
print(gcd(32, 8)) # 8




