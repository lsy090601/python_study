# 3!
# 팩토리얼 : 1부터 n까지의 곱

'''
1!  : 1
2!  : 1 * 2
3!  : 1 * 2 * 3
---------------------------
3!  : 2! * 3
4!  : 3! * 4
n! == (n - 1)! * n
'''

# 반복문을 이용한 팩토리얼 구현
def factorial(n):
    result = 1 # 결과를 저장할 변수
    for i in range(1, n + 1):
        result *= i
    return result

print(factorial(5)) # 120
print(factorial(6)) # 720

# 재귀함수로 구현

def factorial2(n): # 공식 --> n! == (n - 1)! * n
    if n == 1:
        return 1
    return factorial2(n - 1) * n

print(factorial2(5)) # 120
print(factorial2(6)) # 720


def factorial3(n): # 공식 --> n! == (n - 1)! * n
    if n != 1:
        return factorial2(n - 1) * n
    return 1


