# 연산자
#

# 산술 연산자
# +-*/

# //    : 몫의 값을 계산하는 연산자
# %     : 나머지 값을 계산하는 연산자
# **    : 제곱값을 계산하는 연산자

# 대입 연산자
# =
# A = B라고 할 때
# B의 계산 결과를 A 공간에 대입하는 연산자


# 단항 연산자

# A += B의 형태를 가진다.
# B의 계산결과를 A변수(공간)에다가 대입연산자에 붙어있는 산술연산을 진행한다.

num = 10
num += 15 # --> num = num + 15
print(num) # 25


# 비교 연산자
# <, > , <=, >=, == , !=
# 결과값은 True, False 을 반환한다.

# 논리 연산자
# 논리 데이터값을 연결해주는 연산자
# and or not

# A, B를 각각 논리 데이터값이라고 했을 때

# A and B   : A와 B 모두 True일 경우에만 True를 반환한다.

# A or B    : A나 B 중 하나라도 True 라면 True를 반환한다.

# not A     : A가 True라면 False로 False라면 True로 반환한다.





















































































