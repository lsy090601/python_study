

# 시퀸스 연산자
# 시퀸스 순서(index)가 있는 자료형(리스트, 튜플, 문자열 등)에서의 연산자
# +     : 두 컬렉션을 연결해서 새로운 컬렉션데이터를 생성
# *     : 요소가 반복된 새로운 컬렉션데이터를 생성

tree = "*"
space = " "
print(space * 4 + tree)
print(space * 3 + tree * 3)
print(space * 2 + tree * 5)
print(space * 1 + tree * 7)
print(space * 0 + tree * 9)

# formatting
print(f"{tree*7:^9}")
print(f"{tree*5:^9}")
print(f"{tree*3:^9}")
print(f"{tree*1:^9}")
